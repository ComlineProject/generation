//! The `src/` tree a `lib`-mode build emits, as a namespace tree plus the few
//! decisions that genuinely differ per target.
//!
//! Both generators grew their own version of this — `ModuleTree` in
//! `comline-codegen-rust`, `NamespaceTree` in `comline-codegen-typescript` —
//! and they were deliberately *not* unified when the second was written,
//! because one type covering both looked like two implementations behind one
//! name. That judgement deserved revisiting rather than assuming, so here is
//! what measuring found.
//!
//! **Identical in both:** building the tree from `/`-joined namespaces,
//! ordering it (alphabetical, for output stable enough to diff and to put in
//! a content-addressed store), refusing a namespace that is both a schema and
//! a parent of deeper schemas, and the walk that emits a file per node.
//!
//! **Genuinely different, and so asked of the target:** the file extension,
//! where a grouping node's own file goes (`src/group.rs` beside
//! `src/group/`, versus `src/group/index.ts` inside it), the line that
//! declares a child, and which top-level names are reserved (`lib` is the
//! Rust crate root; TypeScript has no equivalent).
//!
//! That is four small decisions against roughly seventy lines of shared
//! structure — which is what makes this worth sharing rather than a shared
//! name over two implementations.

use std::collections::BTreeMap;

use comline_core::schema::ir::frozen::unit::FrozenUnit;
use eyre::{bail, Result};

use crate::GeneratedFile;

/// The target-specific decisions [`NamespaceTree`] needs.
pub trait TreeLayout {
    /// Source file extension, no leading dot (`"rs"`, `"ts"`).
    fn ext(&self) -> &str;

    /// Where a grouping node's own file goes. `prefix` is the node's path
    /// (`"src"` for the root, `"src/group"` for a `group` node).
    ///
    /// Rust puts it beside the directory (`src/group.rs`), with the crate
    /// root a special case (`src/lib.rs`, not `src.rs`); TypeScript puts it
    /// inside (`src/group/index.ts`).
    fn group_file(&self, prefix: &str, is_root: bool) -> String;

    /// The line a grouping node writes to expose one child.
    fn declare_child(&self, segment: &str, child_is_leaf: bool) -> String;

    /// Top-level names this target cannot accept as a schema.
    fn reserved_roots(&self) -> &[&str] {
        &[]
    }

    /// What goes at the top of a generated grouping file.
    fn group_header(&self) -> &str {
        "// Generated by Comline\n\n"
    }

    /// Why this target can't have `path` be both a schema and a namespace —
    /// appended to the refusal so the message names the real conflict.
    fn ambiguity_reason(&self, path: &str) -> String {
        format!("`{path}` would have to be two files at once")
    }

    /// Why `name` can't be a top-level schema.
    fn reserved_root_reason(&self, name: &str) -> String {
        format!("`{name}` is reserved by this target")
    }
}

/// A package's namespaces as a tree. A node is either a schema (leaf) or a
/// grouping of deeper namespaces — never both.
#[derive(Debug)]
pub struct NamespaceTree<'a> {
    #[allow(clippy::type_complexity)]
    schema: Option<(&'a str, &'a [FrozenUnit])>,
    // Alphabetical rather than first-seen: deterministic output matters more
    // than mirroring the order schemas happened to arrive in.
    children: BTreeMap<String, NamespaceTree<'a>>,
}

impl<'a> NamespaceTree<'a> {
    fn empty() -> Self {
        Self {
            schema: None,
            children: BTreeMap::new(),
        }
    }

    pub fn build(
        schemas: &'a [(String, Vec<FrozenUnit>)],
        layout: &dyn TreeLayout,
    ) -> Result<Self> {
        let mut root = Self::empty();
        for (namespace, units) in schemas {
            let mut segments = namespace.split('/');
            if let Some(first) = segments.clone().next() {
                if layout.reserved_roots().contains(&first) {
                    bail!(
                        "can't generate `{namespace}`: {}",
                        layout.reserved_root_reason(first)
                    )
                }
            }
            let mut node = &mut root;
            for segment in segments.by_ref() {
                node = node
                    .children
                    .entry(segment.to_string())
                    .or_insert_with(Self::empty);
            }
            node.schema = Some((namespace.as_str(), units));
        }
        root.check_unambiguous("", layout)?;
        Ok(root)
    }

    fn check_unambiguous(&self, path: &str, layout: &dyn TreeLayout) -> Result<()> {
        if self.schema.is_some() && !self.children.is_empty() {
            bail!(
                "can't generate `{path}`: it's both a schema and a namespace of \
                 deeper schemas (e.g. `{path}/x`) - {}. Rename one of them.",
                layout.ambiguity_reason(path)
            )
        }
        for (segment, child) in &self.children {
            let child_path = if path.is_empty() {
                segment.clone()
            } else {
                format!("{path}/{segment}")
            };
            child.check_unambiguous(&child_path, layout)?;
        }
        Ok(())
    }

    /// Every file this tree needs under `root_dir`, with `render` producing a
    /// schema's own source.
    pub fn emit(
        &self,
        root_dir: &str,
        layout: &dyn TreeLayout,
        render: &dyn Fn(&str, &[FrozenUnit]) -> String,
    ) -> Vec<GeneratedFile> {
        let mut files = Vec::new();
        self.emit_into(root_dir, true, layout, render, &mut files);
        files
    }

    fn emit_into(
        &self,
        prefix: &str,
        is_root: bool,
        layout: &dyn TreeLayout,
        render: &dyn Fn(&str, &[FrozenUnit]) -> String,
        files: &mut Vec<GeneratedFile>,
    ) {
        let mut declarations = String::from(layout.group_header());
        for (segment, child) in &self.children {
            declarations.push_str(&layout.declare_child(segment, child.schema.is_some()));
        }
        files.push(GeneratedFile {
            path: layout.group_file(prefix, is_root).into(),
            contents: declarations,
        });

        for (segment, child) in &self.children {
            let child_prefix = format!("{prefix}/{segment}");
            match child.schema {
                Some((namespace, units)) => files.push(GeneratedFile {
                    path: format!("{child_prefix}.{}", layout.ext()).into(),
                    contents: render(namespace, units),
                }),
                None => child.emit_into(&child_prefix, false, layout, render, files),
            }
        }
    }
}

/// Layouts and helpers shared by this module's test modules.
#[cfg(test)]
mod tests_support {
    use super::*;

    /// A Rust-shaped layout: the grouping file sits beside the directory, the
    /// crate root is `lib.rs`, and `lib` is reserved.
    pub struct RustLike;
    impl TreeLayout for RustLike {
        fn ext(&self) -> &str {
            "rs"
        }
        fn group_file(&self, prefix: &str, is_root: bool) -> String {
            if is_root {
                format!("{prefix}/lib.rs")
            } else {
                format!("{prefix}.rs")
            }
        }
        fn declare_child(&self, segment: &str, _leaf: bool) -> String {
            format!("pub mod {segment};\n")
        }
        fn reserved_roots(&self) -> &[&str] {
            &["lib"]
        }
    }

    /// A TypeScript-shaped layout: a barrel inside the directory, and the
    /// child's own kind decides the specifier.
    pub struct TsLike;
    impl TreeLayout for TsLike {
        fn ext(&self) -> &str {
            "ts"
        }
        fn group_file(&self, prefix: &str, _is_root: bool) -> String {
            format!("{prefix}/index.ts")
        }
        fn declare_child(&self, segment: &str, leaf: bool) -> String {
            let module = if leaf {
                format!("./{segment}.js")
            } else {
                format!("./{segment}/index.js")
            };
            format!("export * as {segment} from \"{module}\";\n")
        }
    }

    pub fn schemas(names: &[&str]) -> Vec<(String, Vec<FrozenUnit>)> {
        names.iter().map(|n| (n.to_string(), vec![])).collect()
    }

    pub fn paths(files: &[GeneratedFile]) -> Vec<String> {
        files
            .iter()
            .map(|f| f.path.to_string_lossy().into_owned())
            .collect()
    }

    pub fn blank(_ns: &str, _u: &[FrozenUnit]) -> String {
        String::new()
    }
}

#[cfg(test)]
mod tests {
    pub use super::tests_support::*;
    use super::*;

    #[test]
    fn a_rust_tree_puts_a_group_file_beside_its_directory() {
        let all = schemas(&["top", "group/first", "group/second"]);
        let tree = NamespaceTree::build(&all, &RustLike).unwrap();
        let files = tree.emit("src", &RustLike, &blank);
        let mut got = paths(&files);
        got.sort();
        assert_eq!(
            got,
            vec![
                "src/group.rs",
                "src/group/first.rs",
                "src/group/second.rs",
                "src/lib.rs",
                "src/top.rs",
            ]
        );
    }

    #[test]
    fn a_typescript_tree_puts_a_barrel_inside_its_directory() {
        let all = schemas(&["top", "group/first"]);
        let tree = NamespaceTree::build(&all, &TsLike).unwrap();
        let files = tree.emit("src", &TsLike, &blank);
        let mut got = paths(&files);
        got.sort();
        assert_eq!(
            got,
            vec![
                "src/group/first.ts",
                "src/group/index.ts",
                "src/index.ts",
                "src/top.ts",
            ]
        );
    }

    #[test]
    fn a_group_declares_its_children_and_only_its_children() {
        let all = schemas(&["top", "group/first", "group/second"]);
        let tree = NamespaceTree::build(&all, &RustLike).unwrap();
        let files = tree.emit("src", &RustLike, &blank);
        let root = files
            .iter()
            .find(|f| f.path.to_str() == Some("src/lib.rs"))
            .unwrap();
        assert!(root.contents.contains("pub mod top;"));
        assert!(root.contents.contains("pub mod group;"));
        assert!(
            !root.contents.contains("first"),
            "the root names `group`, not what is inside it: {}",
            root.contents
        );

        let group = files
            .iter()
            .find(|f| f.path.to_str() == Some("src/group.rs"))
            .unwrap();
        assert!(group.contents.contains("pub mod first;"));
        assert!(group.contents.contains("pub mod second;"));
    }

    #[test]
    fn a_typescript_specifier_depends_on_whether_the_child_is_a_schema() {
        let all = schemas(&["leaf", "group/inner"]);
        let tree = NamespaceTree::build(&all, &TsLike).unwrap();
        let files = tree.emit("src", &TsLike, &blank);
        let root = files
            .iter()
            .find(|f| f.path.to_str() == Some("src/index.ts"))
            .unwrap();
        assert!(root
            .contents
            .contains("export * as leaf from \"./leaf.js\";"));
        assert!(root
            .contents
            .contains("export * as group from \"./group/index.js\";"));
    }

    #[test]
    fn a_schema_that_is_also_a_namespace_is_refused() {
        let all = schemas(&["group", "group/inner"]);
        let err = NamespaceTree::build(&all, &RustLike)
            .unwrap_err()
            .to_string();
        assert!(err.contains("both a schema and a namespace"), "got: {err}");
        assert!(err.contains("group"), "names the conflict: {err}");
    }

    #[test]
    fn the_refusal_carries_the_targets_own_reason() {
        struct Loud;
        impl TreeLayout for Loud {
            fn ext(&self) -> &str {
                "x"
            }
            fn group_file(&self, p: &str, _: bool) -> String {
                format!("{p}/mod.x")
            }
            fn declare_child(&self, s: &str, _: bool) -> String {
                format!("{s}\n")
            }
            fn ambiguity_reason(&self, _path: &str) -> String {
                "THE TARGET SAYS WHY".to_string()
            }
        }
        let all = schemas(&["a", "a/b"]);
        let err = NamespaceTree::build(&all, &Loud).unwrap_err().to_string();
        assert!(err.contains("THE TARGET SAYS WHY"), "got: {err}");
    }

    #[test]
    fn a_reserved_root_is_refused_with_the_targets_reason() {
        let all = schemas(&["lib"]);
        let err = NamespaceTree::build(&all, &RustLike)
            .unwrap_err()
            .to_string();
        assert!(err.contains("lib"), "got: {err}");

        // ...and a target with no reserved roots accepts the same name.
        assert!(NamespaceTree::build(&all, &TsLike).is_ok());
    }

    #[test]
    fn a_reserved_name_deeper_in_a_namespace_is_fine() {
        // Only the top-level segment is a crate root; `group/lib` is an
        // ordinary module.
        let all = schemas(&["group/lib"]);
        assert!(NamespaceTree::build(&all, &RustLike).is_ok());
    }

    #[test]
    fn rendering_receives_each_schemas_own_namespace() {
        let all = schemas(&["top", "group/first"]);
        let tree = NamespaceTree::build(&all, &RustLike).unwrap();
        let files = tree.emit("src", &RustLike, &|ns, _| format!("// {ns}\n"));
        let first = files
            .iter()
            .find(|f| f.path.to_str() == Some("src/group/first.rs"))
            .unwrap();
        assert_eq!(first.contents, "// group/first\n");
    }

    #[test]
    fn a_single_schema_still_gets_a_root_file() {
        let all = schemas(&["only"]);
        let tree = NamespaceTree::build(&all, &RustLike).unwrap();
        let files = tree.emit("src", &RustLike, &blank);
        assert_eq!(paths(&files).len(), 2, "the root plus the schema");
    }
}

/// Parity with the two generators this replaced.
///
/// A shared abstraction is only worth having if it reproduces what it
/// replaces. These assert the exact layouts the committed conformance
/// goldens hold for the `nested_namespace` fixture — `generation`'s
/// `conformance/tests/golden/nested_namespace/{rust,typescript}/` — so a
/// divergence shows up here rather than as golden drift in another repo.
#[cfg(test)]
mod parity {
    use super::tests_support::*;
    use super::*;

    const FIXTURE: &[&str] = &["top", "group/first", "group/second"];

    #[test]
    fn matches_the_rust_generators_committed_layout() {
        let all = schemas(FIXTURE);
        let files = NamespaceTree::build(&all, &RustLike)
            .unwrap()
            .emit("src", &RustLike, &blank);
        let mut got = paths(&files);
        got.sort();
        assert_eq!(
            got,
            vec![
                "src/group.rs",
                "src/group/first.rs",
                "src/group/second.rs",
                "src/lib.rs",
                "src/top.rs",
            ],
            "the Rust `lib` golden's file set"
        );
    }

    #[test]
    fn matches_the_typescript_generators_committed_layout() {
        let all = schemas(FIXTURE);
        let files = NamespaceTree::build(&all, &TsLike)
            .unwrap()
            .emit("src", &TsLike, &blank);
        let mut got = paths(&files);
        got.sort();
        assert_eq!(
            got,
            vec![
                "src/group/first.ts",
                "src/group/index.ts",
                "src/group/second.ts",
                "src/index.ts",
                "src/top.ts",
            ],
            "the TypeScript `lib` golden's file set"
        );
    }

    #[test]
    fn reproduces_the_rust_root_module_file_exactly() {
        let all = schemas(FIXTURE);
        let files = NamespaceTree::build(&all, &RustLike)
            .unwrap()
            .emit("src", &RustLike, &blank);
        let root = files
            .iter()
            .find(|f| f.path.to_str() == Some("src/lib.rs"))
            .unwrap();
        assert_eq!(
            root.contents,
            "// Generated by Comline\n\npub mod group;\npub mod top;\n"
        );
    }

    #[test]
    fn reproduces_the_typescript_group_barrel_exactly() {
        let all = schemas(FIXTURE);
        let files = NamespaceTree::build(&all, &TsLike)
            .unwrap()
            .emit("src", &TsLike, &blank);
        let group = files
            .iter()
            .find(|f| f.path.to_str() == Some("src/group/index.ts"))
            .unwrap();
        assert_eq!(
            group.contents,
            "// Generated by Comline\n\n\
             export * as first from \"./first.js\";\n\
             export * as second from \"./second.js\";\n"
        );
    }
}
